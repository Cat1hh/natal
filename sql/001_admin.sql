CREATE OR REPLACE FUNCTION public.admin_record_change() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $fn$
DECLARE r jsonb := to_jsonb(NEW);
BEGIN
  INSERT INTO public.admin_audit_log(actor_id,community_slug,entity_type,entity_id,action,details)
  VALUES (coalesce(r->>'updated_by','system'),coalesce(r->>'community_slug',r->>'slug'),TG_TABLE_NAME,
    coalesce(r->>'id',r->>'user_id',r->>'slug'),lower(TG_OP),
    jsonb_strip_nulls(jsonb_build_object('name',r->>'name','status',r->>'status','role',r->>'role','ownerUserId',r->>'owner_user_id')));
  RETURN NEW;
END $fn$;
REVOKE ALL ON FUNCTION public.admin_record_change() FROM PUBLIC;
DO $body$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['communities','community_memberships','community_staff','community_events'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS admin_changes ON public.%I',t);
    EXECUTE format('CREATE TRIGGER admin_changes AFTER INSERT OR UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.admin_record_change()',t);
  END LOOP;
END $body$;
-- A decisão, os pontos e a auditoria são gravados na mesma transação.
CREATE OR REPLACE FUNCTION public.admin_moderate_item(
  p_kind text,p_id bigint,p_community text,p_action text,p_actor text,p_points integer[]
) RETURNS jsonb LANGUAGE plpgsql SET search_path = pg_catalog,public AS $fn$
DECLARE s public.submissions; found_id bigint; score integer;
BEGIN
  IF p_actor IS NULL OR p_actor = '' THEN RAISE EXCEPTION 'Actor required'; END IF;
  IF p_kind = 'submissions' AND p_action IN ('approve','reject') THEN
    SELECT * INTO s FROM public.submissions WHERE id=p_id AND community=p_community AND status='pending' FOR UPDATE;
    IF NOT FOUND THEN RETURN jsonb_build_object('ok',false); END IF;
    IF p_action='approve' THEN
      score := p_points[s.day];
      IF score IS NULL OR score < 0 OR score > 10000 THEN RAISE EXCEPTION 'Invalid mission points'; END IF;
      INSERT INTO public.completions(user_id,day,points,community) VALUES(s.user_id,s.day,score,p_community)
      ON CONFLICT (user_id,day,community) DO NOTHING;
    END IF;
    UPDATE public.submissions SET status=CASE p_action WHEN 'approve' THEN 'approved' ELSE 'rejected' END WHERE id=p_id;
  ELSIF p_kind='gallery' AND p_action IN ('approve','reject') THEN
    UPDATE public.gallery SET status=CASE p_action WHEN 'approve' THEN 'approved' ELSE 'rejected' END
    WHERE id=p_id AND community=p_community AND status='pending' RETURNING id INTO found_id;
    IF NOT FOUND THEN RETURN jsonb_build_object('ok',false); END IF;
  ELSIF p_kind='letters' AND p_action='hide' THEN
    UPDATE public.letters SET hidden=true WHERE id=p_id AND community=p_community AND hidden=false RETURNING id INTO found_id;
    IF NOT FOUND THEN RETURN jsonb_build_object('ok',false); END IF;
  ELSE RAISE EXCEPTION 'Invalid moderation operation';
  END IF;
  INSERT INTO public.admin_audit_log(actor_id,community_slug,entity_type,entity_id,action)
  VALUES(p_actor,p_community,p_kind,p_id::text,p_action);
  RETURN jsonb_build_object('ok',true);
END $fn$;
REVOKE ALL ON FUNCTION public.admin_moderate_item(text,bigint,text,text,text,integer[]) FROM PUBLIC;

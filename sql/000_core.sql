BEGIN;
CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL,
  email text UNIQUE,
  discord_id text UNIQUE,
  google_id text UNIQUE,
  avatar text,
  password_hash text,
  community text NOT NULL DEFAULT 'thekingdom',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx ON public.users (lower(email)) WHERE email IS NOT NULL;
CREATE TABLE IF NOT EXISTS public.sessions (
  id text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON public.sessions(expires_at);
CREATE TABLE IF NOT EXISTS public.communities (
  slug text PRIMARY KEY,
  name text NOT NULL,
  tag text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  subtitle text NOT NULL DEFAULT '',
  owner_name text NOT NULL DEFAULT 'Vulpora',
  status text NOT NULL DEFAULT 'ativa' CHECK (status IN ('ativa','preparacao','suspensa')),
  visibility text NOT NULL DEFAULT 'publica' CHECK (visibility IN ('publica','privada')),
  entry_mode text NOT NULL DEFAULT 'livre' CHECK (entry_mode IN ('livre','aprovacao')),
  members_count integer NOT NULL DEFAULT 0 CHECK (members_count >= 0),
  primary_color text NOT NULL DEFAULT '#6d28d9',
  secondary_color text NOT NULL DEFAULT '#172036',
  accent_color text NOT NULL DEFAULT '#c4b5fd',
  hero_title text NOT NULL DEFAULT '',
  hero_subtitle text NOT NULL DEFAULT '',
  symbol text NOT NULL DEFAULT '✦',
  cover_url text NOT NULL DEFAULT '',
  events jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.community_memberships (
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  community_slug text NOT NULL REFERENCES public.communities(slug),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','rejected','blocked')),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id,community_slug)
);
CREATE TABLE IF NOT EXISTS public.completions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  day smallint NOT NULL CHECK (day BETWEEN 1 AND 25),
  points integer NOT NULL CHECK (points >= 0),
  community text NOT NULL REFERENCES public.communities(slug),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id,day,community)
);
CREATE TABLE IF NOT EXISTS public.submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  day smallint NOT NULL CHECK (day BETWEEN 1 AND 25),
  proof text NOT NULL CHECK (length(proof) <= 500),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  community text NOT NULL REFERENCES public.communities(slug),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id,day,community)
);
CREATE TABLE IF NOT EXISTS public.letters (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  author text NOT NULL,
  text text NOT NULL,
  community text NOT NULL REFERENCES public.communities(slug),
  hidden boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.letter_reads (
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  letter_id bigint NOT NULL REFERENCES public.letters(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id,letter_id)
);
CREATE TABLE IF NOT EXISTS public.gallery (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  author_name text NOT NULL,
  title text NOT NULL,
  message text NOT NULL DEFAULT '',
  image_url text NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  community text NOT NULL REFERENCES public.communities(slug),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS membership_scope_status_idx ON public.community_memberships(community_slug,status);
CREATE INDEX IF NOT EXISTS submissions_scope_status_idx ON public.submissions(community,status);
CREATE INDEX IF NOT EXISTS gallery_scope_status_idx ON public.gallery(community,status);
CREATE INDEX IF NOT EXISTS letters_scope_idx ON public.letters(community,hidden,id DESC);
CREATE INDEX IF NOT EXISTS completions_scope_idx ON public.completions(community,user_id);
